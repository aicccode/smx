#!/usr/bin/env python3
"""Generate ``smx/_sm3_core.py``, the fully unrolled SM3 compression function.

Run ``python tools/gen_sm3_core.py`` and then ``ruff format smx/_sm3_core.py``.

In CPython a local variable is the cheapest thing to read, so the generated code
uses one local per schedule word, literal round constants and register renaming
instead of register moves. That is about 14% faster than the same formulas in a
loop, and writing it by hand would invite typos.
"""

from __future__ import annotations

from pathlib import Path

MASK = "0xFFFFFFFF"
# x * DOUBLE holds x twice, so (x * DOUBLE >> 32 - n) & MASK is a left rotation by n.
DOUBLE = "0x100000001"
HEADER = '''"""Unrolled SM3 compression. Generated by tools/gen_sm3_core.py; do not edit."""

from __future__ import annotations

from struct import Struct
from typing import Tuple

_iter_blocks = Struct(">16I").iter_unpack


def compress_blocks(state: Tuple[int, ...], data) -> Tuple[int, ...]:
    """Absorb ``data``, a bytes-like object of whole 64-byte blocks."""
    a0, b0, c0, d0, e0, f0, g0, h0 = state
    for block in _iter_blocks(data):
        w0, w1, w2, w3, w4, w5, w6, w7, w8, w9, w10, w11, w12, w13, w14, w15 = block
'''
FOOTER = """        a0 ^= {0}
        b0 ^= {1}
        c0 ^= {2}
        d0 ^= {3}
        e0 ^= {4}
        f0 ^= {5}
        g0 ^= {6}
        h0 ^= {7}
    return a0, b0, c0, d0, e0, f0, g0, h0
"""


def round_constant(j: int) -> int:
    base = 0x79CC4519 if j < 16 else 0x7A879D8A
    shift = j % 32
    return ((base << shift) | (base >> (32 - shift))) & 0xFFFFFFFF


def schedule_lines() -> list[str]:
    lines = []
    for j in range(16, 68):
        lines += [
            f"y = (w{j - 16} ^ w{j - 9} ^ (w{j - 3} * {DOUBLE} >> 17)) & {MASK}",
            f"z = y * {DOUBLE}",
            f"w{j} = (y ^ (z >> 17) ^ (z >> 9) ^ (w{j - 13} << 7) ^ (w{j - 13} >> 25) ^ w{j - 6}) & {MASK}",
        ]
    return lines


def round_lines() -> tuple[list[str], list[str]]:
    a, b, c, d, e, f, g, h = "abcdefgh"
    lines = [f"{r}, {s} = {r}0, {s}0" for r, s in ("ae", "bf", "cg", "dh")]
    for j in range(64):
        if j < 16:
            ff = f"({a} ^ {b} ^ {c})"
            gg = f"({e} ^ {f} ^ {g})"
        else:
            ff = f"(({a} & {b}) | ({c} & ({a} | {b})))"
            gg = f"({g} ^ ({e} & ({f} ^ {g})))"
        lines += [
            f"u = {a} * {DOUBLE} >> 20 & {MASK}",
            f"x = (u + {e} + {round_constant(j):#010x}) & {MASK}",
            f"x = x * {DOUBLE} >> 25 & {MASK}",
            f"{d} = ({ff} + {d} + (x ^ u) + (w{j} ^ w{j + 4})) & {MASK}",
            f"y = ({gg} + {h} + x + w{j}) & {MASK}",
            f"z = y * {DOUBLE}",
            f"{h} = (y ^ (z >> 23) ^ (z >> 15)) & {MASK}",
            f"{b} = {b} * {DOUBLE} >> 23 & {MASK}",
            f"{f} = {f} * {DOUBLE} >> 13 & {MASK}",
        ]
        a, b, c, d, e, f, g, h = d, a, b, c, h, e, f, g
    return lines, [a, b, c, d, e, f, g, h]


def main() -> None:
    target = Path(__file__).resolve().parents[1] / "smx" / "_sm3_core.py"
    rounds, final = round_lines()
    body = schedule_lines() + rounds
    text = (
        HEADER + "".join(f"        {line}\n" for line in body) + FOOTER.format(*final)
    )
    target.write_text(text)


if __name__ == "__main__":
    main()
