#!/usr/bin/env python3
"""Generate ``smx/_sm9_fq12.py``, unrolled multiplication kernels for SM9's Fq12.

Run ``python tools/gen_sm9_fq12.py`` and then ``ruff format smx/_sm9_fq12.py``.

Fq12 is kept as twelve integers c0..c11, the coefficients of 1, w, ..., w^11 with
w^12 = -2 (w^6 = u, u^2 = -2). Splitting x = A + B*w^6 gives one Karatsuba level:
x*y = AC - 2BD + ((A+B)(C+D) - AC - BD) w^6, with three schoolbook products of
degree-5 polynomials. Products are summed unreduced and each output coefficient is
reduced once. In CPython a local variable is the cheapest thing to read, and every
arithmetic operation costs about the same whatever its operands, so the kernels are
written out term by term: 108 products for a multiplication, 63 for a squaring and
54 for the sparse multiplication by a Miller-loop line.
"""

from __future__ import annotations

from pathlib import Path

HEADER = '''"""Unrolled Fq12 kernels for SM9. Generated by tools/gen_sm9_fq12.py; do not edit.

An element is a tuple of twelve integers, the coefficients of 1, w, ..., w^11 in
Fq[w]/(w^12 + 2). Inputs may be any non-negative integers below a small multiple of
q; outputs are reduced to [0, q).
"""

from __future__ import annotations

Q = 0xB640000002A3A6F1D603AB4FF58EC74521F2934B1A7AEEDBE56F9B27E351457D
'''


def poly_product(a: str, b: str, a_terms, b_terms) -> dict[int, list[str]]:
    """Schoolbook product of two polynomials given by lists of coefficient indices."""
    terms: dict[int, list[str]] = {}
    for i in a_terms:
        for j in b_terms:
            terms.setdefault(i + j, []).append(f"{a}{i} * {b}{j}")
    return terms


def poly_square(a: str, d: str, size: int) -> dict[int, list[str]]:
    """Square of a polynomial; ``d`` names the doubled coefficients."""
    terms: dict[int, list[str]] = {}
    for i in range(size):
        terms.setdefault(2 * i, []).append(f"{a}{i} * {a}{i}")
        for j in range(i + 1, size):
            terms.setdefault(i + j, []).append(f"{d}{i} * {a}{j}")
    return terms


def joined(terms: dict[int, list[str]], k: int) -> str:
    return " + ".join(terms.get(k, [])) or "0"


def combine(low: str, high: str, middle: str, top: int) -> list[str]:
    """Output coefficients of low - 2 high + middle w^6 for products of degree < top."""
    out = []
    for k in range(12):
        if k < 6:
            parts = [f"{low}{k}", f"- 2 * {high}{k}"]
            if k + 6 < top:
                parts.append(f"- 2 * {middle}{k + 6}")
        else:
            parts = [f"{middle}{k - 6}"]
            if k < top:
                parts += [f"+ {low}{k}", f"- 2 * {high}{k}"]
        out.append(f"({' '.join(parts)}) % q")
    return out


def emit_products(lines, names_terms, top) -> None:
    for k in range(top):
        for name, terms, extra in names_terms:
            lines.append(f"    {name}{k} = {joined(terms, k)}{extra(k)}")


def gen_mul() -> list[str]:
    lines = [
        "",
        "",
        "def mul(x: tuple, y: tuple) -> tuple:",
        '    """Return x * y."""',
        "    a0, a1, a2, a3, a4, a5, b0, b1, b2, b3, b4, b5 = x",
        "    c0, c1, c2, c3, c4, c5, d0, d1, d2, d3, d4, d5 = y",
        "    q = Q",
    ]
    for prefix, left, right in (("s", "a", "b"), ("t", "c", "d")):
        names = ", ".join(f"{prefix}{i}" for i in range(6))
        values = ", ".join(f"{left}{i} + {right}{i}" for i in range(6))
        lines.append(f"    {names} = {values}")
    six = range(6)
    ac = poly_product("a", "c", six, six)
    bd = poly_product("b", "d", six, six)
    st = poly_product("s", "t", six, six)
    emit_products(
        lines,
        (
            ("e", ac, lambda k: ""),
            ("f", bd, lambda k: ""),
            ("g", st, lambda k: f" - e{k} - f{k}"),
        ),
        11,
    )
    lines.append("    return (")
    lines += [f"        {term}," for term in combine("e", "f", "g", 11)]
    lines.append("    )")
    return lines


def gen_sqr() -> list[str]:
    lines = [
        "",
        "",
        "def sqr(x: tuple) -> tuple:",
        '    """Return x * x; 2AB is computed as (A + B)^2 - A^2 - B^2."""',
        "    a0, a1, a2, a3, a4, a5, b0, b1, b2, b3, b4, b5 = x",
        "    q = Q",
        "    "
        + ", ".join(f"s{i}" for i in range(6))
        + " = "
        + ", ".join(f"a{i} + b{i}" for i in range(6)),
        "    "
        + ", ".join(f"da{i}" for i in range(5))
        + " = "
        + ", ".join(f"a{i} + a{i}" for i in range(5)),
        "    "
        + ", ".join(f"db{i}" for i in range(5))
        + " = "
        + ", ".join(f"b{i} + b{i}" for i in range(5)),
        "    "
        + ", ".join(f"ds{i}" for i in range(5))
        + " = "
        + ", ".join(f"s{i} + s{i}" for i in range(5)),
    ]
    aa = poly_square("a", "da", 6)
    bb = poly_square("b", "db", 6)
    ss = poly_square("s", "ds", 6)
    emit_products(
        lines,
        (
            ("e", aa, lambda k: ""),
            ("f", bb, lambda k: ""),
            ("g", ss, lambda k: f" - e{k} - f{k}"),
        ),
        11,
    )
    lines.append("    return (")
    lines += [f"        {term}," for term in combine("e", "f", "g", 11)]
    lines.append("    )")
    return lines


def gen_mul_line() -> list[str]:
    """x times a line l0 + l2 w^2 + l3 w^3 + (l6 + l8 w^2 + l9 w^3) w^6."""
    lines = [
        "",
        "",
        "def mul_line(x: tuple, l0: int, l2: int, l3: int, l6: int, l8: int, l9: int) -> tuple:",
        '    """Return x times the sparse element l0 + l2 w^2 + l3 w^3 + l6 w^6 + l8 w^8 + l9 w^9."""',
        "    a0, a1, a2, a3, a4, a5, b0, b1, b2, b3, b4, b5 = x",
        "    q = Q",
        "    "
        + ", ".join(f"s{i}" for i in range(6))
        + " = "
        + ", ".join(f"a{i} + b{i}" for i in range(6)),
        "    c0, c2, c3, d0, d2, d3 = l0, l2, l3, l6, l8, l9",
        "    t0, t2, t3 = c0 + d0, c2 + d2, c3 + d3",
    ]
    six = range(6)
    sparse = (0, 2, 3)
    ac = poly_product("a", "c", six, sparse)
    bd = poly_product("b", "d", six, sparse)
    st = poly_product("s", "t", six, sparse)
    emit_products(
        lines,
        (
            ("e", ac, lambda k: ""),
            ("f", bd, lambda k: ""),
            ("g", st, lambda k: f" - e{k} - f{k}"),
        ),
        9,
    )
    lines.append("    return (")
    lines += [f"        {term}," for term in combine("e", "f", "g", 9)]
    lines.append("    )")
    return lines


def main() -> None:
    source = HEADER + "\n".join(gen_mul() + gen_sqr() + gen_mul_line()) + "\n"
    target = Path(__file__).resolve().parents[1] / "smx" / "_sm9_fq12.py"
    target.write_text(source)


if __name__ == "__main__":
    main()
