#!/usr/bin/env python3
"""Turns testvectors/sm9-vectors.json into test_sm9_vectors.h for test_sm9.c.

Usage (from c/): python3 tools/gen_sm9_vectors.py > test_sm9_vectors.h

Every vector of the JSON goes in: the worked examples of GB/T 38635.5 and the extra ones, the
latter under the extra master keys with the default hid. Strings are UTF-8, written with octal
escapes so that no C hex escape can run into the next character.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
JSON = os.path.join(HERE, "..", "..", "testvectors", "sm9-vectors.json")


def cstr(value):
    if value is None:
        return "NULL"
    out = '"'
    for b in value.encode("utf-8"):
        c = chr(b)
        if c in '"\\?':
            out += "\\" + c
        elif 0x20 <= b < 0x7F:
            out += c
        else:
            out += "\\%03o" % b
    return out + '"'


def row(values):
    return "    {" + ", ".join(values) + "},"


def main():
    with open(JSON, encoding="utf-8") as f:
        d = json.load(f)
    p, std, ext = d["params"], d["standard"], d["extra"]
    print("/* Generated by tools/gen_sm9_vectors.py from testvectors/sm9-vectors.json. */")
    print("/* clang-format off */")
    print("#define SM9V_P1 %s" % cstr(p["P1"]))
    print("#define SM9V_P2 %s" % cstr(p["P2"]))
    print("#define SM9V_MAX_MASTER_KEY %s" % cstr(d["max_valid_master_private_key"]))
    print()

    print("static const struct { const char *mpri, *mpub, *id; int hid; const char *upri, "
          "*msg_hex, *r, *pairing_g, *sig; } sm9v_sign[] = {")
    s = std["sign"]
    print(row([cstr(s["master_private_key"]), cstr(s["master_public_key"]), cstr(s["user_id"]),
               str(s["hid"]), cstr(s["user_private_key"]), cstr(s["message"].encode().hex()),
               cstr(s["r"]), cstr(s["pairing_g"]), cstr(s["signature"])]))
    for e in ext["sign"]:
        print(row([cstr(ext["sign_master_private_key"]), cstr(ext["sign_master_public_key"]),
                   cstr(e["user_id"]), str(p["hid_sign"]), cstr(e["user_private_key"]),
                   cstr(e["message_hex"]), cstr(e["r"]), "NULL", cstr(e["signature"])]))
    print("};\n")

    print("static const struct { const char *mpri, *mpub, *id; int hid; const char *upri, "
          "*msg_hex, *r, *ct_stream, *ct_sm4; } sm9v_encrypt[] = {")
    s = std["encrypt"]
    print(row([cstr(s["master_private_key"]), cstr(s["master_public_key"]), cstr(s["user_id"]),
               str(s["hid"]), cstr(s["user_private_key"]), cstr(s["plaintext"].encode().hex()),
               cstr(s["r"]), cstr(s["ciphertext_stream"]), cstr(s["ciphertext_sm4"])]))
    for e in ext["encrypt"]:
        print(row([cstr(ext["enc_master_private_key"]), cstr(ext["enc_master_public_key"]),
                   cstr(e["user_id"]), str(p["hid_encrypt"]), cstr(e["user_private_key"]),
                   cstr(e["plaintext_hex"]), cstr(e["r"]), cstr(e["ciphertext_stream"]),
                   cstr(e["ciphertext_sm4"])]))
    print("};\n")

    print("static const struct { const char *mpri, *mpub, *id; int hid; const char *upri; "
          "size_t key_len; const char *r, *ct, *key; } sm9v_kem[] = {")
    s = std["encapsulate"]
    print(row([cstr(s["master_private_key"]), cstr(s["master_public_key"]), cstr(s["user_id"]),
               str(s["hid"]), cstr(s["user_private_key"]), str(s["key_len"]), cstr(s["r"]),
               cstr(s["ciphertext"]), cstr(s["key"])]))
    for e in ext["encapsulate"]:
        print(row([cstr(ext["enc_master_private_key"]), cstr(ext["enc_master_public_key"]),
                   cstr(e["user_id"]), str(p["hid_encrypt"]), cstr(e["user_private_key"]),
                   str(e["key_len"]), cstr(e["r"]), cstr(e["ciphertext"]), cstr(e["key"])]))
    print("};\n")

    print("static const struct { const char *mpri, *mpub; int hid; const char *id_a, *id_b, "
          "*upri_a, *upri_b; size_t key_len; const char *r_a, *r_b, *big_ra, *big_rb, *sk, "
          "*s_b, *s_a; } sm9v_exchange[] = {")
    keys = ["id_a", "id_b", "user_private_key_a", "user_private_key_b"]
    tail = ["r_a", "r_b", "R_a", "R_b", "shared_key", "s_b", "s_a"]
    s = std["exchange"]
    print(row([cstr(s["master_private_key"]), cstr(s["master_public_key"]), str(s["hid"])] +
              [cstr(s[k]) for k in keys] + [str(s["key_len"])] + [cstr(s[k]) for k in tail]))
    for e in ext["exchange"]:
        print(row([cstr(ext["enc_master_private_key"]), cstr(ext["enc_master_public_key"]),
                   str(p["hid_exchange"])] + [cstr(e[k]) for k in keys] + [str(e["key_len"])] +
                  [cstr(e[k]) for k in tail]))
    print("};\n")

    for group in ("g1", "g2"):
        print("static const struct { const char *name, *value; } sm9v_invalid_%s[] = {" % group)
        for e in d["invalid_points"][group]:
            print(row([cstr(e["name"]), cstr(e["value"])]))
        print("};\n")
    print("static const struct { const char *name, *value; } sm9v_invalid_scalars[] = {")
    for e in d["invalid_scalars"]:
        print(row([cstr(e["name"]), cstr(e["value"])]))
    print("};")


if __name__ == "__main__":
    sys.exit(main())
