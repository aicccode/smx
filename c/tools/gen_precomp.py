#!/usr/bin/env python3
"""Generates sm2_precomp.inc: fixed tables of multiples of the SM2 generator.

Build-time tool only; the library does not need Python. Uses plain integers on
affine coordinates, so it shares no code with the C field arithmetic it feeds:
a C bug cannot hide in the tables, and test_internal.c re-derives every entry
through a separate slow reference.

Usage: gen_precomp.py [comb_bits] > sm2_precomp.inc
"""
import sys

P = 0xFFFFFFFEFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF00000000FFFFFFFFFFFFFFFF
N = 0xFFFFFFFEFFFFFFFFFFFFFFFFFFFFFFFF7203DF6B21C6052B53BBF40939D54123
A = P - 3
GX = 0x32C4AE2C1F1981195F9904466A39C9948FE30BBFF2660BE1715A4589334C74C7
GY = 0xBC3736A2F4F6779C59BDCEE36B692153D0A9877CC62A474002DF32E52139F0A0


def add(p, q):
    if p is None:
        return q
    if q is None:
        return p
    if p[0] == q[0]:
        if (p[1] + q[1]) % P == 0:
            return None
        lam = (3 * p[0] * p[0] + A) * pow(2 * p[1], -1, P) % P
    else:
        lam = (q[1] - p[1]) * pow(q[0] - p[0], -1, P) % P
    x = (lam * lam - p[0] - q[0]) % P
    return (x, (lam * (p[0] - x) - p[1]) % P)


def limbs(v):
    return [(v >> (64 * i)) & 0xFFFFFFFFFFFFFFFF for i in range(4)]


def row(point):
    words = limbs(point[0]) + limbs(point[1])
    return "{" + ", ".join(f"0x{w:016X}ULL" for w in words) + "}"


def main():
    comb_bits = int(sys.argv[1]) if len(sys.argv) > 1 else 5
    windows = 256 // comb_bits + 1
    entries = 1 << (comb_bits - 1)
    naf_entries = 64  # odd multiples 1G, 3G, ..., 127G (wNAF width 8)

    G = (GX, GY)
    print("/* Generated by tools/gen_precomp.py; do not edit. */")
    print("/* clang-format off */")
    print(f"#define SMX_COMB_BITS {comb_bits}")
    print(f"#define SMX_COMB_WINDOWS {windows}")
    print(f"#define SMX_COMB_ENTRIES {entries}")
    print(f"#define SMX_NAF_G_WIDTH 8")
    print(f"#define SMX_NAF_G_ENTRIES {naf_entries}")
    print()
    print("/* sm2_comb[i][j] = (j + 1) * 2^(comb_bits * i) * G, as x[4], y[4] */")
    print("static const uint64_t sm2_comb[SMX_COMB_WINDOWS][SMX_COMB_ENTRIES][8] = {")
    base = G
    for _ in range(windows):
        print("{")
        cur = base
        for _ in range(entries):
            print(row(cur) + ",")
            cur = add(cur, base)
        print("},")
        for _ in range(comb_bits):
            base = add(base, base)
    print("};")
    print()
    print("/* sm2_naf_g[j] = (2j + 1) * G, as x[4], y[4] */")
    print("static const uint64_t sm2_naf_g[SMX_NAF_G_ENTRIES][8] = {")
    cur = G
    twice = add(G, G)
    for _ in range(naf_entries):
        print(row(cur) + ",")
        cur = add(cur, twice)
    print("};")
    print("/* clang-format on */")


if __name__ == "__main__":
    main()
