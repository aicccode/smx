#!/usr/bin/env python3
"""Prints the constants of sm9_const.h, from the curve parameters in testvectors/sm9_ref.py.

Field elements are in Montgomery form (x * 2^256 mod q), as four little-endian 64-bit limbs.
Usage: python3 tools/gen_sm9_const.py > sm9_const.h
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "testvectors"))
import sm9_ref as R  # noqa: E402

Q, N, T = R.Q, R.N, R.T
RR = 1 << 256


def limbs(v):
    return ", ".join("0x%016XULL" % ((v >> (64 * i)) & (2**64 - 1)) for i in range(4))


def mont(v):
    return "{{%s}}" % limbs(v * RR % Q)


def mont2(a):
    return "{%s, %s}" % (mont(a[0]), mont(a[1]))


def raw(name, v):
    print("static const uint64_t %s[4] = {%s};" % (name, limbs(v)))


out = []
print("/* Generated by tools/gen_sm9_const.py. Field constants are in Montgomery form. */")
print("/* clang-format off */")
print("#ifndef SMX_SM9_CONST_H\n#define SMX_SM9_CONST_H\n")
print("#include <stdint.h>\n")
raw("SM9_Q", Q)
print("#define SM9_Q0 0x%016XULL /* -1/q mod 2^64 */" % ((-pow(Q, -1, 2**64)) % 2**64))
raw("SM9_Q_R2", RR * RR % Q)
raw("SM9_Q_MINUS_2", Q - 2)
raw("SM9_N", N)
print("#define SM9_N0 0x%016XULL /* -1/n mod 2^64 */" % ((-pow(N, -1, 2**64)) % 2**64))
raw("SM9_N_R2", RR * RR % N)
raw("SM9_N_MINUS_1", N - 1)
raw("SM9_N_MINUS_2", N - 2)
print("/* 6t + 2, the Miller loop count, and the trace 6t^2 + 1 of E over Fq */")
print("#define SM9_ATE_LOOP_HI 0x%XULL" % ((6 * T + 2) >> 64))
print("#define SM9_ATE_LOOP_LO 0x%016XULL" % ((6 * T + 2) & (2**64 - 1)))
print("#define SM9_T 0x%016XULL" % T)
raw("SM9_TRACE", 6 * T * T + 1)
print()
print("#define SM9_FQ_ONE_INIT %s" % mont(1))
print("#define SM9_FQ_FIVE_INIT %s" % mont(5))
print("#define SM9_P1_X_INIT %s" % mont(R.P1[0]))
print("#define SM9_P1_Y_INIT %s" % mont(R.P1[1]))
print("#define SM9_P2_X_INIT %s" % mont2(R.P2[0]))
print("#define SM9_P2_Y_INIT %s" % mont2(R.P2[1]))
print("/* twist Frobenius: pi(x, y) = (conj(x) * PI_X, conj(y) * PI_Y); both lie in Fq */")
assert R._PI_X[1] == 0 and R._PI_Y[1] == 0
print("#define SM9_PI_X_INIT %s" % mont(R._PI_X[0]))
print("#define SM9_PI_Y_INIT %s" % mont(R._PI_Y[0]))
print("/* Fq12 Frobenius x^(q^k): coefficient of w^j times gamma_k^j, gamma_k = u^((q^k - 1) / 6), in Fq */")
for k in (1, 2, 3):
    g = R.f2_pow((0, 1), (Q**k - 1) // 6)
    gj = R.F2_ONE
    vals = []
    for j in range(6):
        assert gj[1] == 0
        vals.append(mont(gj[0]))
        gj = R.f2_mul(gj, g)
    print("#define SM9_FROB%d_INIT { \\\n    %s}" % (k, ", \\\n    ".join(vals)))
print("\n#endif /* SMX_SM9_CONST_H */")
