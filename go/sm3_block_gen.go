//go:build ignore

// This program generates sm3_block.go: go run sm3_block_gen.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math/bits"
	"os"
)

func main() {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	p("// Code generated by sm3_block_gen.go. DO NOT EDIT.")
	p("")
	p("package smx")
	p("")
	p("import (\n\t\"encoding/binary\"\n\t\"math/bits\"\n)")
	p("")
	p("// sm3Blocks runs the compression function over whole 64-byte blocks. All 64 rounds are")
	p("// written out with the working variables renamed instead of moved, and the message")
	p("// expansion is computed just in time in a 16-word window, so W never goes to an array.")
	p("// The round constants T_j <<< j are folded in as literals.")
	p("func sm3Blocks(v *[8]uint32, p []byte) {")
	p("h0, h1, h2, h3, h4, h5, h6, h7 := v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7]")
	p("for len(p) >= sm3BlockSize {")
	p("block := p[:sm3BlockSize:sm3BlockSize]")
	for j := 0; j < 16; j++ {
		p("w%d := binary.BigEndian.Uint32(block[%d:])", j, 4*j)
	}
	p("a, b, c, d, e, f, g, h := h0, h1, h2, h3, h4, h5, h6, h7")
	p("var ss1, r, tt uint32")
	w := func(j int) string { return fmt.Sprintf("w%d", j%16) }
	st := []string{"a", "b", "c", "d", "e", "f", "g", "h"}
	for j := 0; j < 64; j++ {
		A, B, C, D, E, F, G, H := st[0], st[1], st[2], st[3], st[4], st[5], st[6], st[7]
		if k := j + 4; k >= 16 {
			// W[k] replaces W[k-16], which is no longer needed.
			p("tt = %s ^ %s ^ bits.RotateLeft32(%s, 15)", w(k-16), w(k-9), w(k-3))
			p("%s = tt ^ bits.RotateLeft32(tt, 15) ^ bits.RotateLeft32(tt, 23) ^ bits.RotateLeft32(%s, 7) ^ %s",
				w(k), w(k-13), w(k-6))
		}
		t := uint32(0x79CC4519)
		ff := fmt.Sprintf("(%s ^ %s ^ %s)", A, B, C)
		gg := fmt.Sprintf("(%s ^ %s ^ %s)", E, F, G)
		if j >= 16 {
			t = 0x7A879D8A
			ff = fmt.Sprintf("(%s&%s | %s&(%s|%s))", A, B, C, A, B)
			gg = fmt.Sprintf("(%s ^ %s&(%s^%s))", G, E, F, G)
		}
		p("r = bits.RotateLeft32(%s, 12)", A)
		p("ss1 = bits.RotateLeft32(r+%s+0x%08X, 7)", E, bits.RotateLeft32(t, j%32))
		p("%s += %s + (ss1 ^ r) + (%s ^ %s)", D, ff, w(j), w(j+4))
		p("tt = %s + %s + ss1 + %s", gg, H, w(j))
		p("%s = bits.RotateLeft32(%s, 9)", B, B)
		p("%s = bits.RotateLeft32(%s, 19)", F, F)
		p("%s = tt ^ bits.RotateLeft32(tt, 9) ^ bits.RotateLeft32(tt, 17)", H)
		// The new A is D and the new E is H.
		st = []string{D, A, B, C, H, E, F, G}
	}
	p("h0 ^= a\nh1 ^= b\nh2 ^= c\nh3 ^= d\nh4 ^= e\nh5 ^= f\nh6 ^= g\nh7 ^= h")
	p("p = p[sm3BlockSize:]")
	p("}")
	p("v[0], v[1], v[2], v[3], v[4], v[5], v[6], v[7] = h0, h1, h2, h3, h4, h5, h6, h7")
	p("}")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("sm3_block.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
