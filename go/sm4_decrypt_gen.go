//go:build ignore

// This program generates sm4_decrypt.go: go run sm4_decrypt_gen.go
//
// CBC decryption has no chaining between block-cipher calls, so several blocks can run
// their table rounds interleaved. Each round of one block waits on the previous one,
// and interleaving lets the CPU overlap the table loads of independent blocks. Go keeps
// only scalar variables in registers, so each width is written out by this generator.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
)

// Widths of the generated group functions, widest first.
var widths = []int{8, 4, 2, 1}

func main() {
	var b bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	p("// Code generated by sm4_decrypt_gen.go. DO NOT EDIT.")
	p("")
	p("package smx")
	p("")
	p(`import "encoding/binary"`)
	p("")
	p("// sm4CBCDecryptTable decrypts whole blocks of buf in place with the table rounds,")
	p("// chaining from iv. Runs of blocks are interleaved %d, %d, %d or %d at a time.", widths[0], widths[1], widths[2], widths[3])
	p("func sm4CBCDecryptTable(drk *[32]uint32, iv *[16]byte, buf []byte) {")
	p("prev := [4]uint32{")
	for k := 0; k < 4; k++ {
		p("binary.BigEndian.Uint32(iv[%d:]),", 4*k)
	}
	p("}")
	for i, n := range widths {
		loop := "if"
		if i == 0 {
			loop = "for"
		}
		p("%s len(buf) >= %d {", loop, 16*n)
		p("sm4DecryptGroup%d(drk, &prev, buf[:%d:%d])", n, 16*n, 16*n)
		p("buf = buf[%d:]", 16*n)
		p("}")
	}
	p("}")
	for _, n := range widths {
		group(p, n)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("sm4_decrypt.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// group writes the function that CBC-decrypts exactly n blocks, chaining from prev and
// leaving the last ciphertext block in prev.
func group(p func(string, ...any), n int) {
	p("")
	p("// sm4DecryptGroup%d CBC-decrypts the %d blocks of buf in place.", n, n)
	p("func sm4DecryptGroup%d(drk *[32]uint32, prev *[4]uint32, buf []byte) {", n)
	p("_ = buf[%d]", 16*n-1)
	p("t := &sm4Tab.t")
	// s[j][k] is word k of block j's state; c[j][k] keeps its ciphertext for chaining.
	s := make([][4]string, n)
	for j := 0; j < n; j++ {
		for k := 0; k < 4; k++ {
			s[j][k] = fmt.Sprintf("s%d_%d", j, k)
			p("c%d_%d := binary.BigEndian.Uint32(buf[%d:])", j, k, 16*j+4*k)
		}
	}
	for j := 0; j < n; j++ {
		p("%s, %s, %s, %s := c%d_0, c%d_1, c%d_2, c%d_3", s[j][0], s[j][1], s[j][2], s[j][3], j, j, j, j)
	}
	x := make([]string, n)
	for j := range x {
		x[j] = fmt.Sprintf("x%d", j)
	}
	p("var %s uint32", join(x))
	p("for i := 0; i < 32; i += 4 {")
	for r := 0; r < 4; r++ {
		for j := 0; j < n; j++ {
			p("x%d = %s ^ %s ^ %s ^ drk[i+%d]", j, s[j][(r+1)%4], s[j][(r+2)%4], s[j][(r+3)%4], r)
		}
		for j := 0; j < n; j++ {
			p("%s ^= t[0][x%d>>24] ^ t[1][byte(x%d>>16)] ^ t[2][byte(x%d>>8)] ^ t[3][byte(x%d)]", s[j][r], j, j, j, j)
		}
	}
	p("}")
	// The cipher output is the state in reverse word order.
	for j := 0; j < n; j++ {
		for k := 0; k < 4; k++ {
			chain := fmt.Sprintf("prev[%d]", k)
			if j > 0 {
				chain = fmt.Sprintf("c%d_%d", j-1, k)
			}
			p("binary.BigEndian.PutUint32(buf[%d:], %s^%s)", 16*j+4*k, s[j][3-k], chain)
		}
	}
	p("prev[0], prev[1], prev[2], prev[3] = c%d_0, c%d_1, c%d_2, c%d_3", n-1, n-1, n-1, n-1)
	p("}")
}

func join(v []string) string {
	var b bytes.Buffer
	for i, s := range v {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(s)
	}
	return b.String()
}
