const sm4CbcKat = <int, String>{
  0: '7eb90905271950e540bc2a2ae758039e189c25e9ad7b5478969b09192e2aead1',
  1: 'a2a9b9360dca5bb7d613a5488f9395dec7fb463a7000f532c9e49b4a609252d6',
  15: '95fd050bc0da54661213a2443e2fcc12246b6fd1904d39cf594e16791c2730ea',
  16: '63295c1fadc1d3fa637ded988c7d6ebb4b60406421527d45a5cf742914151f45',
  17: 'c6e49d0f4b4f127a4e306c53b268e107c325945ce1b319e01cd40a3ae786eb7a',
  31: 'eea3e428c1d992d9401e6ede569470c93ac658f446b1cda22db9107536be3ffb',
  32: '4262f3191131c48ba325b29700803638fc076940df5c4f88c3dc3a007d8ff648',
  100: '34982382c690d09878fe1e4ac39f8e299d3aec85bfc2b5199deda5e9abd7ddc3',
  1000: '5b2c9193a8fbcec78c571cb16bd95cecb089c53c5f88df5ba782d193e5fa6f4c',
  4096: '85e4ca14dbb58c6f1162dbd3ccbb10ea4588341123bcc2af21ed6d2e71cbd771',
};

final Matcher throwsSmx = throwsA(isA<SmxException>());

Matcher throwsDecryptError() => throwsA(isA<SmxException>()
    .having((e) => e.message, 'message', 'decryption failed'));

SM4 make(List<int> key, List<int> iv) => SM4()..setKey(key, iv);

void main() {
  final standardKey = hexToBytes('0123456789abcdeffedcba9876543210');
  final ascii16 = utf8.encode('0123456789abcdef');

  group('known answers', () {
    test('GB/T 32907 single block', () {
      final cipher = make(standardKey, Uint8List(16));
      final block = cipher.encryptBlock(standardKey);
      expect(bytesToHex(block), '681edf34d206965e86b3e94f536e4246');
      expect(cipher.decryptBlock(block), standardKey);
    });

    test('GB/T 32907 one million iterations', () {
      final cipher = make(standardKey, Uint8List(16));
      var block = standardKey;
      for (var i = 0; i < 1000000; i++) {
        block = cipher.encryptBlock(block);
      }
      expect(bytesToHex(block), '595298c7c6fd271f0402f804c33d3f66');
      for (var i = 0; i < 1000000; i++) {
        block = cipher.decryptBlock(block);
      }
      expect(block, standardKey);
    });

    test('raw 16-byte key vector generated by Go', () {
      final cipher = make(ascii16, Uint8List(16));
      expect(cipher.encrypt('Hello from Go Client!'),
          '91ea70533805dcf27e8c42bbd0b27cda20be69aae26e297643247ba61f083719');
    });

    test('pinned CBC ciphertexts', () {
      final cipher = make(det(16, 'k'), det(16, 'iv'));
      sm4CbcKat.forEach((length, expected) {
        final plaintext = hexOf(det(length, 'p')).substring(0, length);
        final ciphertext = cipher.encrypt(plaintext);
        expect(sha256Hex(ascii.encode(ciphertext)), expected,
            reason: '$length');
        expect(cipher.decrypt(ciphertext), plaintext);
        expect(cipher.encryptBytes(ascii.encode(plaintext)), ciphertext);
        expect(cipher.decryptBytes(ciphertext), ascii.encode(plaintext));
      });
    });
  });

  group('behaviour', () {
    test('round trip at block boundaries', () {
      final cipher = make(ascii16, utf8.encode('fedcba9876543210'));
      for (final length in [0, 1, 15, 16, 17, 32, 100]) {
        final message = 'x' * length;
        final ciphertext = cipher.encrypt(message);
        expect(ciphertext.length, (length ~/ 16 + 1) * 32);
        expect(cipher.decrypt(ciphertext), message);
      }
      expect(cipher.decrypt(cipher.encrypt('国密 SM4 😀')), '国密 SM4 😀');
    });

    test('encrypt is repeatable: the IV is not chained between calls', () {
      final cipher = make(ascii16, Uint8List(16));
      expect(cipher.encrypt('same'), cipher.encrypt('same'));
    });

    test('use before setKey throws', () {
      final cipher = SM4();
      expect(() => cipher.encrypt('x'), throwsSmx);
      expect(() => cipher.decrypt('00' * 16), throwsSmx);
      expect(() => cipher.encryptBlock(Uint8List(16)), throwsSmx);
    });

    test('raw block operations reject the wrong size', () {
      final cipher = make(ascii16, Uint8List(16));
      for (final bad in [<int>[], Uint8List(15), Uint8List(17)]) {
        expect(() => cipher.encryptBlock(bad), throwsSmx);
        expect(() => cipher.decryptBlock(bad), throwsSmx);
      }
      expect(() => cipher.encryptBlock(List<int>.filled(16, 256)), throwsSmx);
    });

    test('decrypt rejects malformed and tampered ciphertext', () {
      final cipher = make(ascii16, Uint8List(16));
      for (final bad in ['', 'abc', 'zz' * 16, '00' * 15]) {
        expect(() => cipher.decrypt(bad), throwsDecryptError(), reason: bad);
        expect(() => cipher.decryptBytes(bad), throwsDecryptError());
      }
      // CBC with a zero IV: this decrypts to 16 zero bytes, invalid padding.
      final forged = bytesToHex(cipher.encryptBlock(Uint8List(16)));
      expect(() => cipher.decrypt(forged), throwsDecryptError());
      final good = cipher.encrypt('hello');
      expect(() => cipher.decrypt(good.toUpperCase()), throwsDecryptError());
    });

    test('invalid UTF-8 plaintext fails decrypt but not decryptBytes', () {
      final cipher = make(ascii16, Uint8List(16));
      final ciphertext = cipher.encryptBytes([0xff, 0xfe, 0x41]);
      expect(() => cipher.decrypt(ciphertext), throwsDecryptError());
      expect(cipher.decryptBytes(ciphertext), [0xff, 0xfe, 0x41]);
    });

    test('lone surrogates are not valid text', () {
      final cipher = make(ascii16, Uint8List(16));
      for (final bad in ['\uD800', 'a\uDC00b', '\uD83D']) {
        expect(() => cipher.encrypt(bad), throwsSmx);
      }
    });

    test('non-byte plaintext elements are rejected', () {
      final cipher = make(ascii16, Uint8List(16));
      expect(() => cipher.encryptBytes([1, 256]), throwsSmx);
    });

    test('toString does not show key material', () {
      expect(make(ascii16, Uint8List(16)).toString(), 'SM4()');
    });

    test('PKCS#7 helpers', () {
      expect(pkcs7Pad([]), List<int>.filled(16, 16));
      expect(pkcs7Pad(List<int>.filled(15, 0x61)),
          [...List<int>.filled(15, 0x61), 1]);
      expect(pkcs7Unpad(pkcs7Pad(utf8.encode('abc'))), utf8.encode('abc'));
      for (final bad in [
        <int>[],
        [...List<int>.filled(15, 0x61), 0],
        [...List<int>.filled(15, 0x61), 0x11],
        [...List<int>.filled(14, 0x61), 1, 2],
      ]) {
        expect(() => pkcs7Unpad(bad), throwsDecryptError());
      }
    });

    test('ECB padded helpers round trip', () {
      final key = det(16, 'ecb');
      for (final length in [0, 1, 15, 16, 17, 100]) {
        final data = det(length, 'data');
        final c = sm4EcbEncryptPadded(key, data);
        expect(c.length, (length ~/ 16 + 1) * 16);
        // ECB: each block is the raw block encryption.
        final cipher = make(key, Uint8List(16));
        expect(c.sublist(0, 16),
            cipher.encryptBlock(pkcs7Pad(data).sublist(0, 16)));
        expect(sm4EcbDecryptPadded(key, c), data);
      }
      expect(sm4EcbDecryptPadded(key, []), isNull);
      expect(sm4EcbDecryptPadded(key, Uint8List(15)), isNull);
      expect(sm4EcbDecryptPadded(key, Uint8List(16)), isNull);
      expect(() => sm4EcbEncryptPadded(Uint8List(15), [1]), throwsSmx);
    });
  });

  group('shared security vectors', () {
    final vectors = jsonDecode(
            File('../testvectors/security-vectors.json').readAsStringSync())
        as Map<String, dynamic>;
    final v = vectors['sm4'] as Map<String, dynamic>;
    SM4 makeShared({List<int>? key, List<int>? iv}) => make(
        key ?? hexToBytes(v['key'] as String),
        iv ?? hexToBytes(v['iv'] as String));

    test('valid ciphertexts', () {
      final cipher = makeShared();
      expect(cipher.encrypt(v['valid_padded_plaintext'] as String),
          v['valid_padded_ciphertext']);
      expect(cipher.decrypt(v['valid_padded_ciphertext'] as String),
          v['valid_padded_plaintext']);
    });

    test('full padding block', () {
      final cipher = makeShared();
      final ciphertext = v['valid_full_padding_block_ciphertext'] as String;
      expect(cipher.decrypt(ciphertext), '');
      expect(cipher.encrypt(''), ciphertext);
    });

    test('invalid key and IV lengths', () {
      for (final size in (v['invalid_key_lengths_bytes'] as List).cast<int>()) {
        expect(() => makeShared(key: Uint8List(size)), throwsSmx);
      }
      for (final size in (v['invalid_iv_lengths_bytes'] as List).cast<int>()) {
        expect(() => makeShared(iv: Uint8List(size)), throwsSmx);
      }
    });

    test('every padding and length failure is the same error', () {
      final cipher = makeShared();
      final bad = <String>[
        for (final c in v['invalid_paddings'] as List)
          (c as Map<String, dynamic>)['value'] as String,
        for (final size
            in (v['invalid_ciphertext_lengths_bytes'] as List).cast<int>())
          '00' * size,
        'zz' * 16,
        '0',
      ];
      final messages = <String>{};
      for (final value in bad) {
        try {
          cipher.decrypt(value);
          fail('accepted $value');
        } on SmxException catch (e) {
          messages.add(e.message);
        }
        expect(() => cipher.decryptBytes(value), throwsDecryptError());
      }
      expect(messages, {'decryption failed'});
    });

    test('unpad accepts exactly the valid paddings', () {
      for (final body in [<int>[], List<int>.filled(16, 0x61)]) {
        for (var pad = 0; pad < 256; pad++) {
          for (final lastDiffers in [false, true]) {
            final block = List<int>.filled(16, 0x7a);
            final count = pad < 16 ? pad : 16;
            block.fillRange(16 - count, 16, pad);
            block[15] = pad;
            if (lastDiffers && count > 1) block[14] ^= 1;
            final data = [...body, ...block];
            final valid = pad >= 1 && pad <= 16 && !(lastDiffers && count > 1);
            if (valid) {
              expect(pkcs7Unpad(data), data.sublist(0, data.length - pad));
            } else {
              expect(() => pkcs7Unpad(data), throwsDecryptError(),
                  reason: 'pad $pad');
            }
          }
        }
      }
    });

    test('failed setKey keeps the previous key', () {
      final cipher = makeShared();
      final expected = cipher.encrypt('x');
      expect(() => cipher.setKey(Uint8List(15), Uint8List(16)), throwsSmx);
      expect(() => cipher.setKey(Uint8List(16), Uint8List(17)), throwsSmx);
      expect(cipher.encrypt('x'), expected);
    });
  });
}
