// Generates the unrolled Montgomery field arithmetic in lib/src/field/.
//
//   dart run tool/gen_field.dart
//
// An element is 9 limbs of 29 bits, little endian, stored at an offset in a
// Uint32List. Values are kept in [0, 2m) (lazy reduction). Montgomery's R is
// 2^261 > 4m, so a product of two values below 2m is again below 2m and no
// final subtraction is needed.
import 'dart:io';

const limbBits = 29;
const limbCount = 9;
final limbMask = (1 << limbBits) - 1;

List<int> limbsOf(BigInt v) => [
      for (var i = 0; i < limbCount; i++)
        ((v >> (limbBits * i)) & BigInt.from(limbMask)).toInt(),
    ];

String generate(String prefix, String name, BigInt m) {
  final mod = limbsOf(m);
  final twice = limbsOf(m * BigInt.two);
  final base = BigInt.one << limbBits;
  final n0 = ((-m.modInverse(base)) % base).toInt();
  final o = StringBuffer();
  void w(String s) => o.writeln(s);
  final M = limbMask;

  w('// GENERATED by tool/gen_field.dart. Do not edit by hand.');
  w('//');
  w('// Montgomery arithmetic modulo the $name, 9 limbs of 29 bits.');
  w('// Every function reads all of its inputs before writing the output, so the');
  w('// output may alias an input. No branch or memory index depends on the values.');
  w('// ignore_for_file: lines_longer_than_80_chars');
  w('');
  w("import 'dart:typed_data';");
  w('');
  w('/// Limbs of the modulus.');
  w('const List<int> ${prefix}Modulus = <int>[${mod.join(', ')}];');
  w('');

  String loadA(String v, String src, String off) =>
      'final ' +
      [for (var i = 0; i < limbCount; i++) '$v$i = $src[$off + $i]']
          .join(', ') +
      ';';

  // ---- multiplication
  w('/// r = a * b / R mod m, for a, b in [0, 2m); the result is in [0, 2m).');
  w('void ${prefix}Mul(Uint32List r, int ro, Uint32List x, int xo, Uint32List y, int yo) {');
  w('  ${loadA('a', 'x', 'xo')}');
  w('  ${loadA('b', 'y', 'yo')}');
  w('  int t, c;');
  void reduceTail(int k, List<String> terms) {
    final mterms = [
      for (var i = 0; i < limbCount; i++)
        if (k - i >= 0 && k - i < limbCount && i < k && mod[k - i] != 0)
          'm$i * ${mod[k - i]}',
    ];
    final all = [...terms, ...mterms];
    w('  t = ${k == 0 ? '' : 'c + '}${all.join(' + ')};');
    if (k < limbCount) {
      if (n0 == 1) {
        w('  final m$k = t & $M;');
      } else {
        w('  final m$k = ((t & $M) * $n0) & $M;');
      }
      if (mod[0] != 0) w('  t += m$k * ${mod[0]};');
      w('  c = t >> $limbBits;');
    } else {
      w('  r[ro + ${k - limbCount}] = t & $M;');
      w('  c = t >> $limbBits;');
    }
  }

  for (var k = 0; k < 2 * limbCount - 1; k++) {
    reduceTail(k, [
      for (var i = 0; i < limbCount; i++)
        if (k - i >= 0 && k - i < limbCount) 'a$i * b${k - i}',
    ]);
  }
  w('  r[ro + ${limbCount - 1}] = c;');
  w('}');
  w('');

  // ---- squaring
  w('/// r = a * a / R mod m, for a in [0, 2m); the result is in [0, 2m).');
  w('void ${prefix}Sqr(Uint32List r, int ro, Uint32List x, int xo) {');
  w('  ${loadA('a', 'x', 'xo')}');
  w('  final ' +
      [for (var i = 1; i < limbCount; i++) 'd$i = a$i << 1'].join(', ') +
      ';');
  w('  int t, c;');
  for (var k = 0; k < 2 * limbCount - 1; k++) {
    final terms = <String>[];
    for (var i = 0; i < limbCount; i++) {
      final j = k - i;
      if (j <= i || j >= limbCount) continue;
      // j > i: 2 * a_i * a_j, written as a_i * d_j
      terms.add('a$i * d$j');
    }
    if (k.isEven && k ~/ 2 < limbCount) terms.add('a${k ~/ 2} * a${k ~/ 2}');
    reduceTail(k, terms);
  }
  w('  r[ro + ${limbCount - 1}] = c;');
  w('}');
  w('');

  // ---- conditional subtraction helper, emitted inline
  void condSub(List<String> s, List<int> sub, String target) {
    // d = s - sub; if no borrow, r = d, else r = s.
    w('  t = ${s[0]} - ${sub[0]};');
    w('  final e0 = t & $M;');
    for (var i = 1; i < limbCount; i++) {
      w('  t = ${s[i]} - ${sub[i]} + (t >> $limbBits);');
      w('  final e$i = t & $M;');
    }
    w('  final keep = t >> 63; // all ones when s < sub');
    w('  final take = ~keep;');
    for (var i = 0; i < limbCount; i++) {
      w('  $target[ro + $i] = (${s[i]} & keep) | (e$i & take);');
    }
  }

  // ---- addition
  w('/// r = a + b mod m, for a, b in [0, 2m); the result is in [0, 2m).');
  w('void ${prefix}Add(Uint32List r, int ro, Uint32List x, int xo, Uint32List y, int yo) {');
  w('  int t = x[xo] + y[yo];');
  w('  final s0 = t & $M;');
  for (var i = 1; i < limbCount; i++) {
    w('  t = x[xo + $i] + y[yo + $i] + (t >> $limbBits);');
    w('  final s$i = ${i == limbCount - 1 ? 't' : 't & $M'};');
  }
  condSub([for (var i = 0; i < limbCount; i++) 's$i'], twice, 'r');
  w('}');
  w('');

  // ---- subtraction: a - b + 2m in (0, 4m), then reduce
  w('/// r = a - b mod m, for a, b in [0, 2m); the result is in [0, 2m).');
  w('void ${prefix}Sub(Uint32List r, int ro, Uint32List x, int xo, Uint32List y, int yo) {');
  w('  int t = x[xo] - y[yo] + ${twice[0]};');
  w('  final s0 = t & $M;');
  for (var i = 1; i < limbCount; i++) {
    w('  t = x[xo + $i] - y[yo + $i] + ${twice[i]} + (t >> $limbBits);');
    w('  final s$i = ${i == limbCount - 1 ? 't' : 't & $M'};');
  }
  condSub([for (var i = 0; i < limbCount; i++) 's$i'], twice, 'r');
  w('}');
  w('');

  // ---- negation
  w('/// r = -a mod m, for a in [0, 2m); the result is in [0, 2m).');
  w('void ${prefix}Neg(Uint32List r, int ro, Uint32List x, int xo) {');
  w('  int t = ${twice[0]} - x[xo];');
  w('  final s0 = t & $M;');
  for (var i = 1; i < limbCount; i++) {
    w('  t = ${twice[i]} - x[xo + $i] + (t >> $limbBits);');
    w('  final s$i = ${i == limbCount - 1 ? 't' : 't & $M'};');
  }
  condSub([for (var i = 0; i < limbCount; i++) 's$i'], twice, 'r');
  w('}');
  w('');

  // ---- canonical form
  w('/// r = a reduced into [0, m), for a in [0, 2m).');
  w('void ${prefix}Canon(Uint32List r, int ro, Uint32List x, int xo) {');
  w('  ${loadA('s', 'x', 'xo')}');
  w('  int t;');
  condSub([for (var i = 0; i < limbCount; i++) 's$i'], mod, 'r');
  w('}');
  return o.toString();
}

/// Fused multiplication and squaring in Fq2 = Fq[u]/(u^2 + 2), for the SM9
/// field: unreduced column products are combined first and only the two
/// results are Montgomery-reduced. Column sums stay below 2^63 because every
/// operand limb is below 2^29 (sums are normalized before multiplying).
String generateFq2(String prefix, BigInt m, {required bool square}) {
  final mod = limbsOf(m);
  final base = BigInt.one << limbBits;
  final n0 = ((-m.modInverse(base)) % base).toInt();
  final k8 = [
    for (var i = 0; i < 2 * limbCount; i++)
      (((m * m * BigInt.from(8)) >> (limbBits * i)) & BigInt.from(limbMask))
          .toInt(),
  ];
  if ((m * m * BigInt.from(8)) >> (limbBits * 2 * limbCount) != BigInt.zero) {
    throw StateError('8m^2 does not fit');
  }
  final four = limbsOf(m * BigInt.from(4));
  final M = limbMask;
  final o = StringBuffer();
  void w(String s) => o.writeln(s);

  String load(String v, String src, String off) =>
      'final ' +
      [for (var i = 0; i < limbCount; i++) '$v$i = $src[$off + $i]']
          .join(', ') +
      ';';
  String prod(String x, String y, int k) {
    final t = [
      for (var i = 0; i < limbCount; i++)
        if (k - i >= 0 && k - i < limbCount) '$x$i * $y${k - i}',
    ];
    return t.isEmpty ? '0' : t.join(' + ');
  }

  // Emits one column of a running Montgomery reduction named [tag], whose
  // input limb is [limb] (already normalized), writing limbs at [outOff].
  void redc(String tag, int k, String limb, int outOff) {
    final mterms = [
      for (var i = 0; i < limbCount; i++)
        if (k - i >= 0 && k - i < limbCount && i < k && mod[k - i] != 0)
          '${tag}m$i * ${mod[k - i]}',
    ];
    w('  t = ${tag}c + $limb${mterms.isEmpty ? '' : ' + ${mterms.join(' + ')}'};');
    if (k < limbCount) {
      w('  final ${tag}m$k = ((t & $M) * $n0) & $M;');
      w('  t += ${tag}m$k * ${mod[0]};');
    } else if (k < 2 * limbCount - 1) {
      w('  r[ro + ${outOff + k - limbCount}] = t & $M;');
    } else {
      w('  r[ro + ${outOff + k - limbCount}] = t;');
    }
    w('  ${tag}c = t >> $limbBits;');
  }

  if (!square) {
    // ---- multiplication
    w('/// r = a * b in Fq2 (a = a0 + a1 u at xo, xo + 9), inputs and output in');
    w('/// [0, 2q) per coefficient.');
    w('void ${prefix}2Mul(Uint32List r, int ro, Uint32List x, int xo, Uint32List y, int yo) {');
    w('  ${load('a', 'x', 'xo')}');
    w('  ${load('b', 'x', 'xo + $limbCount')}');
    w('  ${load('c', 'y', 'yo')}');
    w('  ${load('d', 'y', 'yo + $limbCount')}');
    w('  int t;');
    // s = a + b, t = c + d, normalized
    w('  t = 0;');
    for (var i = 0; i < limbCount; i++) {
      w('  t += a$i + b$i;');
      w('  final s$i = ${i == limbCount - 1 ? 't' : 't & $M'};');
      if (i != limbCount - 1) w('  t >>= $limbBits;');
    }
    w('  t = 0;');
    for (var i = 0; i < limbCount; i++) {
      w('  t += c$i + d$i;');
      w('  final e$i = ${i == limbCount - 1 ? 't' : 't & $M'};');
      if (i != limbCount - 1) w('  t >>= $limbBits;');
    }
    w('  var pc = 0, qc = 0, xc = 0, yc = 0; // normalization and REDC carries');
    for (var k = 0; k < 2 * limbCount; k++) {
      if (k < 2 * limbCount - 1) {
        w('  final u$k = ${prod('a', 'c', k)};');
        w('  final v$k = ${prod('b', 'd', k)};');
        w('  final w$k = ${prod('s', 'e', k)};');
        // c0 = u - 2v + 8q^2, c1 = w - u - v
        w('  t = pc + u$k - (v$k << 1) + ${k8[k]};');
        w('  final p$k = t & $M;');
        w('  pc = t >> $limbBits;');
        w('  t = qc + w$k - u$k - v$k;');
        w('  final q$k = t & $M;');
        w('  qc = t >> $limbBits;');
      } else {
        w('  final p$k = pc + ${k8[k]};');
        w('  final q$k = qc;');
      }
      redc('x', k, 'p$k', 0);
      redc('y', k, 'q$k', limbCount);
    }
    w('}');
    w('');

    return o.toString();
  }
  // ---- squaring
  w('/// r = a^2 in Fq2: c0 = (a0 + a1)(a0 - 2 a1 + 4q) + a0 a1, c1 = 2 a0 a1.');
  w('void ${prefix}2Sqr(Uint32List r, int ro, Uint32List x, int xo) {');
  w('  ${load('a', 'x', 'xo')}');
  w('  ${load('b', 'x', 'xo + $limbCount')}');
  w('  int t;');
  w('  t = 0;');
  for (var i = 0; i < limbCount; i++) {
    w('  t += a$i + b$i;');
    w('  final s$i = ${i == limbCount - 1 ? 't' : 't & $M'};');
    if (i != limbCount - 1) w('  t >>= $limbBits;');
  }
  w('  t = 0;');
  for (var i = 0; i < limbCount; i++) {
    w('  t += a$i - (b$i << 1) + ${four[i]};');
    w('  final e$i = ${i == limbCount - 1 ? 't' : 't & $M'};');
    if (i != limbCount - 1) w('  t >>= $limbBits;');
  }
  w('  var pc = 0, qc = 0, xc = 0, yc = 0;');
  for (var k = 0; k < 2 * limbCount; k++) {
    if (k < 2 * limbCount - 1) {
      w('  final u$k = ${prod('s', 'e', k)};');
      w('  final v$k = ${prod('a', 'b', k)};');
      w('  t = pc + u$k + v$k;');
      w('  final p$k = t & $M;');
      w('  pc = t >> $limbBits;');
      w('  t = qc + (v$k << 1);');
      w('  final q$k = t & $M;');
      w('  qc = t >> $limbBits;');
    } else {
      w('  final p$k = pc;');
      w('  final q$k = qc;');
    }
    redc('x', k, 'p$k', 0);
    redc('y', k, 'q$k', limbCount);
  }
  w('}');
  return o.toString();
}

void main() {
  final out = Directory('lib/src/field');
  out.createSync(recursive: true);
  final sm2p = BigInt.parse(
      'FFFFFFFEFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF00000000FFFFFFFFFFFFFFFF',
      radix: 16);
  final sm9q = BigInt.parse(
      'B640000002A3A6F1D603AB4FF58EC74521F2934B1A7AEEDBE56F9B27E351457D',
      radix: 16);
  File('${out.path}/sm2_fp.g.dart')
      .writeAsStringSync(generate('fp', 'SM2 field prime p', sm2p));
  File('${out.path}/sm9_fq.g.dart')
      .writeAsStringSync(generate('fq', 'SM9 field prime q', sm9q));
  for (final square in [false, true]) {
    final name = square ? 'sqr' : 'mul';
    File('${out.path}/sm9_fq2_$name.g.dart').writeAsStringSync(
        '// GENERATED by tool/gen_field.dart. Do not edit by hand.\n'
        '//\n'
        '// Fused Fq2 arithmetic for the SM9 field (see generateFq2).\n'
        '// ignore_for_file: lines_longer_than_80_chars\n\n'
        "import 'dart:typed_data';\n\n"
        '${generateFq2('fq', sm9q, square: square)}');
  }
  stdout.writeln('generated the field files in ${out.path}');
}
