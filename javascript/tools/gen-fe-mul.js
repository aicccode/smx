/**
 * Generates sm2/fe-mul.js, the unrolled Montgomery multipliers.
 *
 *   node tools/gen-fe-mul.js > sm2/fe-mul.js && prettier --write sm2/fe-mul.js
 */
const LIMBS = 11
const N = 0xfffffffeffffffffffffffffffffffff7203df6b21c6052b53bbf40939d54123n
const BASE = 1n << 24n

/** Balanced base-2^24 digits, each in [-2^23, 2^23). */
function balanced(value) {
  const out = []
  let v = value
  for (let i = 0; i < LIMBS; i++) {
    let d = v & (BASE - 1n)
    if (d >= BASE >> 1n) d -= BASE
    out.push(Number(d))
    v = (v - d) >> 24n
  }
  return out
}

function inverseModBase(a) {
  let x = 1n
  for (let i = 0; i < 6; i++) x = (x * (2n - a * x)) & (BASE - 1n)
  return x
}

function product(squared) {
  let s = ''
  for (let i = 0; i < LIMBS; i++) s += `const a${i} = a[${i}]\n`
  if (!squared) for (let i = 0; i < LIMBS; i++) s += `const b${i} = b[${i}]\n`
  for (let k = 0; k < 2 * LIMBS - 1; k++) {
    const terms = []
    for (let i = 0; i < LIMBS; i++) {
      const j = k - i
      if (j < 0 || j >= LIMBS) continue
      if (!squared) terms.push(`a${i} * b${j}`)
      else if (j > i) terms.push(`a${i} * a${j}`)
    }
    let e = terms.join(' + ')
    if (squared) {
      e = terms.length ? `2 * (${e})` : ''
      if (k % 2 === 0) e += `${e ? ' + ' : ''}a${k / 2} * a${k / 2}`
    }
    s += `${k === 0 ? 'const' : 'let'} c${k} = ${e}\n`
  }
  return s
}

/** The columns from 11 up hold the result; the final carry fills the top limb. */
function finish() {
  let s = ''
  for (let i = LIMBS; i < 2 * LIMBS - 1; i++) {
    s += `h = Math.floor(c${i} * INV + 0.5)\n`
    s += `r[${i - LIMBS}] = c${i} - h * BASE\n`
    if (i < 2 * LIMBS - 2) s += `c${i + 1} += h\n`
  }
  return s + `r[${LIMBS - 1}] = h\n`
}

/** p = 2^256 - 2^224 - 2^96 + 2^64 - 1, so -1/p = 1 mod 2^24 and q is the digit. */
function reduceP() {
  let s = 'let h = 0\nlet q = 0\n'
  for (let i = 0; i < LIMBS; i++) {
    s += `h = Math.floor(c${i} * INV + 0.5)\n`
    s += `q = c${i} - h * BASE\n`
    s += `c${i + 1} += h\n`
    s += `c${i + 2} += q * 65536\n`
    s += `c${i + 4} -= q\n`
    s += `c${i + 9} -= q * 256\n`
    s += `c${i + 10} += q * 65536\n`
  }
  return s
}

function reduceN() {
  const limbs = balanced(N)
  let n0inv = (BASE - inverseModBase(N & (BASE - 1n))) & (BASE - 1n)
  if (n0inv >= BASE >> 1n) n0inv -= BASE
  let s = 'let h = 0\nlet lo = 0\nlet q = 0\n'
  for (let i = 0; i < LIMBS; i++) {
    s += `h = Math.floor(c${i} * INV + 0.5)\n`
    s += `lo = c${i} - h * BASE\n`
    s += `q = lo * ${n0inv}\n`
    s += `q -= Math.floor(q * INV + 0.5) * BASE\n`
    s += `c${i + 1} += h + (lo + q * ${limbs[0]}) * INV\n`
    for (let j = 1; j < LIMBS; j++) {
      if (limbs[j] !== 0) s += `c${i + j} += q * ${limbs[j]}\n`
    }
  }
  return s
}

const fn = (name, params, body, doc) =>
  `/** ${doc} */\nexport function ${name}(${params}) {\n${body}}\n\n`

let out = `// Generated by tools/gen-fe-mul.js. Do not edit by hand.
//
// Montgomery multiplication with R = 2^264 on 11 balanced base-2^24 limbs held
// in doubles. All values stay exact integers below 2^53 as long as the operands
// obey the bound documented in fe.js. There are no data-dependent branches.

const BASE = 16777216
const INV = 1 / 16777216

`
out += fn(
  'fpMul',
  'r, a, b',
  product(false) + reduceP() + finish(),
  'r = a * b / R mod p',
)
out += fn(
  'fpSqr',
  'r, a',
  product(true) + reduceP() + finish(),
  'r = a * a / R mod p',
)
out += fn(
  'fnMul',
  'r, a, b',
  product(false) + reduceN() + finish(),
  'r = a * b / R mod n',
)
out += fn(
  'fnSqr',
  'r, a',
  product(true) + reduceN() + finish(),
  'r = a * a / R mod n',
)
process.stdout.write(out.trimEnd() + '\n')
