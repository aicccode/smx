/**
 * Generates sm9/fp-mul.js and sm9/fn-mul.js, the unrolled Montgomery multipliers
 * modulo the SM9 prime q and the group order N. Same technique as tools/gen-fe-mul.js: 11
 * balanced base-2^24 limbs in doubles, R = 2^264, word-by-word reduction.
 *
 *   node tools/gen-sm9-fp-mul.js q > sm9/fp-mul.js
 *   node tools/gen-sm9-fp-mul.js n > sm9/fn-mul.js
 *   prettier --write sm9/fp-mul.js sm9/fn-mul.js
 */
const LIMBS = 11
const Q = 0xb640000002a3a6f1d603ab4ff58ec74521f2934b1a7aeedbe56f9b27e351457dn
const N = 0xb640000002a3a6f1d603ab4ff58ec74449f2934b18ea8beee56ee19cd69ecf25n
const BASE = 1n << 24n

/** Balanced base-2^24 digits, each in [-2^23, 2^23). */
function balanced(value) {
  const out = []
  let v = value
  for (let i = 0; i < LIMBS; i++) {
    let d = v & (BASE - 1n)
    if (d >= BASE >> 1n) d -= BASE
    out.push(Number(d))
    v = (v - d) >> 24n
  }
  if (v !== 0n) throw new Error('modulus does not fit')
  return out
}

function inverseModBase(a) {
  let x = 1n
  for (let i = 0; i < 6; i++) x = (x * (2n - a * x)) & (BASE - 1n)
  return x
}

function product(squared) {
  let s = ''
  for (let i = 0; i < LIMBS; i++) s += `const a${i} = a[${i}]\n`
  if (!squared) for (let i = 0; i < LIMBS; i++) s += `const b${i} = b[${i}]\n`
  for (let k = 0; k < 2 * LIMBS - 1; k++) {
    const terms = []
    for (let i = 0; i < LIMBS; i++) {
      const j = k - i
      if (j < 0 || j >= LIMBS) continue
      if (!squared) terms.push(`a${i} * b${j}`)
      else if (j > i) terms.push(`a${i} * a${j}`)
    }
    let e = terms.join(' + ')
    if (squared) {
      e = terms.length ? `2 * (${e})` : ''
      if (k % 2 === 0) e += `${e ? ' + ' : ''}a${k / 2} * a${k / 2}`
    }
    s += `${k === 0 ? 'const' : 'let'} c${k} = ${e}\n`
  }
  s += `let c${2 * LIMBS - 1} = 0\n`
  return s
}

/** Montgomery reduction, one limb at a time, for a general odd modulus. */
function reduce(modulus) {
  const limbs = balanced(modulus)
  let m0inv = (BASE - inverseModBase(modulus & (BASE - 1n))) & (BASE - 1n)
  if (m0inv >= BASE >> 1n) m0inv -= BASE
  let s = 'let h = 0\nlet lo = 0\nlet q = 0\n'
  for (let i = 0; i < LIMBS; i++) {
    s += `h = Math.floor(c${i} * INV + 0.5)\n`
    s += `lo = c${i} - h * BASE\n`
    s += `q = lo * ${m0inv}\n`
    s += `q -= Math.floor(q * INV + 0.5) * BASE\n`
    s += `c${i + 1} += h + (lo + q * ${limbs[0]}) * INV\n`
    for (let j = 1; j < LIMBS; j++) {
      if (limbs[j] !== 0) s += `c${i + j} += q * ${limbs[j]}\n`
    }
  }
  return s
}

/** The columns from 11 up hold the result; the final carry joins the top limb. */
function finish() {
  let s = ''
  for (let i = LIMBS; i < 2 * LIMBS - 1; i++) {
    s += `h = Math.floor(c${i} * INV + 0.5)\n`
    s += `r[${i - LIMBS}] = c${i} - h * BASE\n`
    s += `c${i + 1} += h\n`
  }
  return s + `r[${LIMBS - 1}] = c${2 * LIMBS - 1}\n`
}

const fn = (name, params, body, doc) =>
  `/** ${doc} */\nexport function ${name}(${params}) {\n${body}}\n\n`

const which = process.argv[2]
if (which !== 'q' && which !== 'n')
  throw new Error('usage: gen-sm9-fp-mul.js q|n')
const [mod, mul, sqr, label] =
  which === 'q' ? [Q, 'fpMul', 'fpSqr', 'q'] : [N, 'fnMul', 'fnSqr', 'N']

let out = `// Generated by tools/gen-sm9-fp-mul.js. Do not edit by hand.
//
// Montgomery multiplication with R = 2^264 on 11 balanced base-2^24 limbs held
// in doubles, modulo the SM9 ${which === 'q' ? 'prime q' : 'group order N'}. All values stay exact integers
// below 2^53 as long as the operands obey the bound documented in sm9/fp.js.
// There are no data-dependent branches.

const BASE = 16777216
const INV = 1 / 16777216

`
out += fn(
  mul,
  'r, a, b',
  product(false) + reduce(mod) + finish(),
  `r = a * b / R mod ${label}`,
)
out += fn(
  sqr,
  'r, a',
  product(true) + reduce(mod) + finish(),
  `r = a * a / R mod ${label}`,
)
process.stdout.write(out.trimEnd() + '\n')
